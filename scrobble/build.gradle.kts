import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import java.util.Properties

// :scrobble — listening history to Last.fm, Libre.fm and ListenBrainz.
//
// Shared by app-linux (MPRIS) and app-android (media sessions): the rules,
// the services and the offline queue live here; only "what is playing"
// comes from the platform.

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.android.library)
}

kotlin {
    jvm("desktop") {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }
    androidTarget {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    sourceSets {
        val commonMain by getting {
            dependencies {
                api(project(":core"))
                implementation(libs.kotlinx.coroutines.core)
                implementation(libs.kotlinx.serialization.json)
            }
        }
        // HTTP and MD5 come from the JVM, which both targets are.
        val jvmMain by creating {
            dependsOn(commonMain)
            kotlin.srcDir(layout.buildDirectory.dir("generated/scrobbleKeys"))
        }
        val desktopMain by getting { dependsOn(jvmMain) }
        val androidMain by getting { dependsOn(jvmMain) }
        val desktopTest by getting {
            dependencies {
                implementation(libs.kotlin.test)
            }
        }
    }
}

android {
    namespace = "dev.lumen.scrobble"
    compileSdk = 36
    defaultConfig {
        minSdk = 26
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

// Last.fm API credentials are NOT in the repository. Last.fm issues them per
// application (https://www.last.fm/api/account/create); a build picks them
// up from `lumen.lastfm.apiKey` / `lumen.lastfm.sharedSecret` in
// ~/.gradle/gradle.properties or local.properties, or from the
// LUMEN_LASTFM_API_KEY / LUMEN_LASTFM_SHARED_SECRET environment variables.
// Without them the app still builds; the Last.fm button explains what is
// missing, and Libre.fm and ListenBrainz work regardless.
val localProps = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}
fun scrobbleKey(prop: String, env: String): String =
    (findProperty(prop) as String?) ?: localProps.getProperty(prop) ?: System.getenv(env) ?: ""
val lastFmApiKey = scrobbleKey("lumen.lastfm.apiKey", "LUMEN_LASTFM_API_KEY")
val lastFmSecret = scrobbleKey("lumen.lastfm.sharedSecret", "LUMEN_LASTFM_SHARED_SECRET")

val generateScrobbleKeys by tasks.registering {
    val out = layout.buildDirectory.file("generated/scrobbleKeys/dev/lumen/scrobble/ScrobbleKeys.kt")
    // Locals, not the script-level vals: the configuration cache cannot
    // serialize a reference back into the build script.
    val key = lastFmApiKey
    val secret = lastFmSecret
    inputs.property("key", key)
    inputs.property("secret", secret)
    outputs.file(out)
    doLast {
        val file = out.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package dev.lumen.scrobble\n\n" +
                "/** Generated by :scrobble:generateScrobbleKeys. Empty when not configured. */\n" +
                "internal object ScrobbleKeys {\n" +
                "    const val LASTFM_API_KEY: String = \"" + key + "\"\n" +
                "    const val LASTFM_SHARED_SECRET: String = \"" + secret + "\"\n" +
                "}\n",
        )
    }
}
tasks.matching { it.name.startsWith("compile") && "Kotlin" in it.name }.configureEach {
    dependsOn(generateScrobbleKeys)
}
